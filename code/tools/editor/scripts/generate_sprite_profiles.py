"""Regenerate the editor's state catalog from this port's canonical info.cpp."""
import pathlib
import re
import json

root = pathlib.Path(__file__).resolve().parents[3]
source = (root / 'code/info.cpp').read_text()
states = []
for m in re.finditer(r'\{SPR_(\w+),(\d+),(-?\d+),\{([^}]*)\},(S_\w+),0,0\},?\s*//\s*(S_\w+)', source):
    sprite, frame, ticks, action, next_state, name = m.groups()
    states.append(dict(sprite=sprite, frame=int(frame) & 32767, ticks=int(ticks),
                       name=name, next=next_state, action=action))
assert states[0]['name'] == 'S_NULL'
by_name = {s['name']: i for i, s in enumerate(states)}
header = (root / 'code/info.h').read_text()
enum_names = re.findall(r'^\s*(S_\w+),', header, re.M)
assert enum_names == [s['name'] for s in states], 'State catalog must match engine enum exactly'
names = {'MT_POSSESSED':'Zombieman', 'MT_SHOTGUY':'Shotgun guy', 'MT_VILE':'Arch-vile',
         'MT_UNDEAD':'Revenant', 'MT_FATSO':'Mancubus', 'MT_CHAINGUY':'Chaingunner',
         'MT_TROOP':'Imp', 'MT_SERGEANT':'Demon', 'MT_SHADOWS':'Spectre',
         'MT_HEAD':'Cacodemon', 'MT_BRUISER':'Baron of Hell', 'MT_KNIGHT':'Hell knight',
         'MT_SKULL':'Lost soul', 'MT_SPIDER':'Spider mastermind', 'MT_BABY':'Arachnotron',
         'MT_CYBORG':'Cyberdemon', 'MT_PAIN':'Pain elemental', 'MT_WOLFSS':'Wolfenstein SS',
         'MT_KEEN':'Commander Keen', 'MT_PLAYER':'Player', 'MT_EGGZOMBIE':'Egg Zombie'}
groups = [('spawnstate','Idle'),('seestate','Walk / run'),('meleestate','Melee'),
          ('missilestate','Shoot / attack'),('painstate','Pain'),('deathstate','Death'),
          ('xdeathstate','Extreme death'),('raisestate','Raise')]
lines = ['// Generated by tools/DoomEd/scripts/generate_sprite_profiles.py. Do not hand edit.',
         '#pragma once', '#include <string>', '#include <vector>', 'namespace doom_sprites {',
         'struct State { int id; const char *name; const char *sprite; int frame, ticks; };',
         'struct Slot { std::string label; std::vector<State> states; };',
         'struct Profile { const char *name; int thingType, spawnState; float height; std::vector<Slot> slots; };',
         'inline const std::vector<Profile> &profiles() {',
         '    static const std::vector<Profile> data = {']
for m in re.finditer(r'\{\s*//\s*(MT_\w+)\s*\n(.*?)\n\s*\}', source, re.S):
    tag, block = m.groups()
    if tag not in names: continue
    fields = dict((key, value.strip().rstrip(',')) for value,key in
                  re.findall(r'^\s*([^\n]+?)\s*//\s*(\w+)\s*$',block,re.M))
    starts = {fields[k] for k,_ in groups if fields.get(k) in by_name and fields[k] != 'S_NULL'}
    slots = []
    assigned_states = set()
    for key,label in groups:
        current = fields.get(key, 'S_NULL')
        if key == 'meleestate' and current == fields.get('missilestate'):
            label = 'Melee / shoot'
        visited = set()
        group_slots = {}
        while current in by_name and current != 'S_NULL' and current not in visited:
            if current in assigned_states: break
            visited.add(current)
            assigned_states.add(current)
            s = states[by_name[current]]
            pair = (s['sprite'], s['frame'])
            if pair not in group_slots:
                group_slots[pair] = len(slots)
                slots.append([f'{label} {len(group_slots)} ({s["sprite"]}{chr(65+s["frame"])})', []])
            slots[group_slots[pair]][1].append(by_name[current])
            current = s['next']
            if current in starts: break
    covered = {i for _, ids in slots for i in ids}
    sprite = states[by_name[fields['spawnstate']]]['sprite']
    for i,s in enumerate(states):
        if tag == 'MT_EGGZOMBIE' and not s['name'].startswith('S_EGGZ_'): continue
        if tag != 'MT_EGGZOMBIE' and s['name'].startswith(('S_EGGZ_', 'S_EGG_FLY', 'S_EGG_WAIT', 'S_EGG_HATCH')): continue
        if i and i not in covered and s['sprite'] == sprite:
            slots.append([f'Special ({s["name"]})', [i]])
    height = int(fields['height'].split('*')[0])
    lines.append(f'        {{{json.dumps(names[tag])}, {fields["doomednum"]}, {by_name[fields["spawnstate"]]}, {height}.0f, {{')
    for label, ids in slots:
        entries = []
        for i in ids:
            s=states[i]
            entries.append(f'{{{i}, "{s["name"]}", "{s["sprite"]}", {s["frame"]}, {s["ticks"]}}}')
        lines.append('            {'+json.dumps(label)+', {'+', '.join(entries)+'}},')
    lines.append('        }},')
lines += ['    };', '    return data;', '}', '} // namespace doom_sprites', '']
(root/'formats/sprite_profiles.h').write_text('\n'.join(lines))
print(f'Generated {len(names)} profiles from {len(states)} engine states')

